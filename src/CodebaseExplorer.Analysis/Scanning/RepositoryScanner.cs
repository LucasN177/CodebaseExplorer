using System.Buffers;
using System.Collections.Concurrent;
using System.Security.Cryptography;
using System.Text;
using CodebaseExplorer.Analysis.FileSystem;
using CodebaseExplorer.Application.Analysis;
using CodebaseExplorer.Application.Repositories;
using CodebaseExplorer.Domain.Common;
using CodebaseExplorer.Domain.Runs;

namespace CodebaseExplorer.Analysis.Scanning;

/// <summary>
/// Stage 1 of the pipeline (ANALYSIS_ENGINE.md). Phase 1 enumerates repository files depth-first
/// (sequentially) with built-in excludes, in-process <c>.gitignore</c> semantics and limits, and never
/// follows links. Phase 2 inspects the files in parallel — hash, line count, binary and generated
/// markers in one pass per file through <see cref="IRepositoryFileReader"/>. Files and diagnostics are
/// sorted, so the result does not depend on the degree of parallelism.
/// </summary>
internal sealed class RepositoryScanner(IRepositoryFileReader fileReader, TimeProvider timeProvider)
{
    public const string AnalyzerName = "scanner";

    private const int SniffLength = 8 * 1024;
    private const int ReadBufferLength = 81920;
    private static readonly TimeSpan ProgressInterval = TimeSpan.FromMilliseconds(100);
    private static readonly byte[] GeneratedMarker = Encoding.ASCII.GetBytes("<auto-generated");

    public async Task<ScanResult> ScanAsync(
        RepositoryRoot root,
        AnalysisLimits limits,
        IProgress<AnalysisProgress>? progress,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(root);
        ArgumentNullException.ThrowIfNull(limits);

        var state = new ScanState(root, limits, progress, timeProvider);
        var excluded = new HashSet<string>(limits.ExcludedDirectoryNames, StringComparer.OrdinalIgnoreCase);

        await EnumerateDirectoryAsync(state, new DirectoryInfo(root.FullPath), string.Empty, 0, excluded, cancellationToken);
        await InspectFilesAsync(state, cancellationToken);

        state.Report(force: true);

        var files = state.Files.OrderBy(f => f.Path.Value, StringComparer.Ordinal).ToArray();
        var diagnostics = state.Diagnostics
            .OrderBy(d => d.Code, StringComparer.Ordinal)
            .ThenBy(d => d.Message, StringComparer.Ordinal)
            .ToArray();

        return new ScanResult(files, state.Statistics with { FilesScanned = files.Length }, diagnostics);
    }

    private async Task EnumerateDirectoryAsync(
        ScanState state,
        DirectoryInfo directory,
        string relativeDirectory,
        int depth,
        HashSet<string> excludedNames,
        CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();

        FileSystemInfo[] entries;
        try
        {
            entries = directory.GetFileSystemInfos();
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            state.Update(s => s with { EntriesUnreadable = s.EntriesUnreadable + 1 });
            state.Warn(RepositoryErrorCodes.FileUnreadable,
                $"{(relativeDirectory.Length == 0 ? "." : relativeDirectory)}: directory could not be listed ({exception.GetType().Name}).");
            return;
        }

        // Deterministic order; the .gitignore of this directory applies to its own entries.
        Array.Sort(entries, (a, b) => string.CompareOrdinal(a.Name, b.Name));
        if (entries.OfType<FileInfo>().Any(f => f.Name == ".gitignore" && f.LinkTarget is null))
        {
            await LoadGitIgnoreAsync(state, Join(relativeDirectory, ".gitignore"), relativeDirectory, cancellationToken);
        }

        foreach (var entry in entries)
        {
            if (state.Statistics.Truncated)
            {
                return;
            }

            var relativePath = Join(relativeDirectory, entry.Name);

            if (entry.LinkTarget is not null)
            {
                state.Update(s => s with { LinksSkipped = s.LinksSkipped + 1 });
                state.Info(RepositoryErrorCodes.FileLinkNotFollowed, $"{relativePath}: symbolic link or junction not followed.");
                continue;
            }

            if (entry is DirectoryInfo subdirectory)
            {
                if (excludedNames.Contains(entry.Name))
                {
                    state.Update(s => s with { DirectoriesExcluded = s.DirectoriesExcluded + 1 });
                }
                else if (state.GitIgnore.IsIgnored(relativePath, isDirectory: true))
                {
                    state.Update(s => s with { DirectoriesIgnored = s.DirectoriesIgnored + 1 });
                }
                else if (depth + 1 > state.Limits.MaxDirectoryDepth)
                {
                    state.Update(s => s with { DirectoriesTooDeep = s.DirectoriesTooDeep + 1 });
                    state.Warn("scan.directory-too-deep", $"{relativePath}: deeper than {state.Limits.MaxDirectoryDepth} levels; skipped.");
                }
                else
                {
                    await EnumerateDirectoryAsync(state, subdirectory, relativePath, depth + 1, excludedNames, cancellationToken);
                }

                continue;
            }

            if (state.GitIgnore.IsIgnored(relativePath, isDirectory: false))
            {
                state.Update(s => s with { FilesIgnored = s.FilesIgnored + 1 });
                continue;
            }

            if (state.Candidates.Count >= state.Limits.MaxFiles)
            {
                state.Update(s => s with { Truncated = true });
                state.Warn("scan.file-limit-reached", $"The scan stopped after {state.Limits.MaxFiles} files.");
                return;
            }

            state.Candidates.Add(RelativePath.Create(relativePath));
        }
    }

    private async Task LoadGitIgnoreAsync(ScanState state, string path, string baseDirectory, CancellationToken cancellationToken)
    {
        var content = await fileReader.ReadAllTextAsync(state.Root, RelativePath.Create(path), state.Limits.MaxManifestBytes, cancellationToken);
        if (content.TryGetValue(out var text, out var error))
        {
            state.GitIgnore.AddFile(baseDirectory, text);
        }
        else
        {
            // Ignored files may now be scanned: always a warning, also for oversized ignore files.
            state.Warn(error.Code, $"{path}: {error.Message} Its ignore rules were not applied.");
        }
    }

    private async Task InspectFilesAsync(ScanState state, CancellationToken cancellationToken)
    {
        var options = new ParallelOptions
        {
            CancellationToken = cancellationToken,
            MaxDegreeOfParallelism = Math.Max(1, state.Limits.MaxDegreeOfParallelism),
        };

        await Parallel.ForEachAsync(state.Candidates, options, async (path, token) =>
        {
            var opened = fileReader.OpenRead(state.Root, path);
            if (!opened.TryGetValue(out var stream, out var error))
            {
                state.Update(s => s with { EntriesUnreadable = s.EntriesUnreadable + 1 });
                state.Diagnostics.Add(FileAccessDiagnostics.From(error, state.Analyzer));
                return;
            }

            try
            {
                await using (stream)
                {
                    state.Files.Add(await InspectAsync(stream, path, token));
                }
            }
            catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
            {
                state.Update(s => s with { EntriesUnreadable = s.EntriesUnreadable + 1 });
                state.Warn(RepositoryErrorCodes.FileUnreadable, $"{path}: could not be read ({exception.GetType().Name}).");
                return;
            }

            state.FileInspected(path.Value);
        });
    }

    private static async Task<ScannedFile> InspectAsync(Stream stream, RelativePath path, CancellationToken cancellationToken)
    {
        using var hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        var buffer = ArrayPool<byte>.Shared.Rent(ReadBufferLength);
        var sniff = new byte[SniffLength];
        var sniffed = 0;
        long size = 0;
        var newlines = 0;
        var lastByte = -1;

        try
        {
            int read;
            while ((read = await stream.ReadAsync(buffer.AsMemory(0, ReadBufferLength), cancellationToken)) > 0)
            {
                var span = buffer.AsSpan(0, read);
                hash.AppendData(span);

                if (sniffed < SniffLength)
                {
                    var take = Math.Min(SniffLength - sniffed, read);
                    span[..take].CopyTo(sniff.AsSpan(sniffed));
                    sniffed += take;
                }

                newlines += span.Count((byte)'\n');
                lastByte = span[^1];
                size += read;
            }
        }
        finally
        {
            ArrayPool<byte>.Shared.Return(buffer);
        }

        var head = sniff.AsSpan(0, sniffed);
        var isBinary = head.Contains((byte)0);
        var hasGeneratedHeader = !isBinary && ContainsIgnoreAsciiCase(head, GeneratedMarker);
        int? lineCount = isBinary ? null : size == 0 ? 0 : newlines + (lastByte == '\n' ? 0 : 1);

        return new ScannedFile(
            path,
            size,
            ContentHash.FromBytes(hash.GetHashAndReset()),
            lineCount,
            isBinary,
            hasGeneratedHeader,
            FileClassifier.Classify(path, isBinary, hasGeneratedHeader));
    }

    private static bool ContainsIgnoreAsciiCase(ReadOnlySpan<byte> haystack, ReadOnlySpan<byte> needle)
    {
        for (var i = 0; i + needle.Length <= haystack.Length; i++)
        {
            var match = true;
            for (var j = 0; j < needle.Length; j++)
            {
                if (char.ToLowerInvariant((char)haystack[i + j]) != char.ToLowerInvariant((char)needle[j]))
                {
                    match = false;
                    break;
                }
            }

            if (match)
            {
                return true;
            }
        }

        return false;
    }

    private static string Join(string directory, string name) => directory.Length == 0 ? name : $"{directory}/{name}";

    private sealed class ScanState(
        RepositoryRoot root,
        AnalysisLimits limits,
        IProgress<AnalysisProgress>? progress,
        TimeProvider timeProvider)
    {
        private readonly Lock _gate = new();
        private long _lastReport = long.MinValue;
        private int _inspected;
        private string? _currentItem;

        public RepositoryRoot Root { get; } = root;

        public AnalysisLimits Limits { get; } = limits;

        public AnalyzerId Analyzer { get; } = AnalyzerId.Create(AnalyzerName);

        public GitIgnoreMatcher GitIgnore { get; } = new();

        /// <summary>Files found in phase 1, in enumeration order.</summary>
        public List<RelativePath> Candidates { get; } = [];

        public ConcurrentBag<ScannedFile> Files { get; } = [];

        public ConcurrentBag<AnalysisDiagnostic> Diagnostics { get; } = [];

        public ScanStatistics Statistics { get; private set; } = new();

        public void Update(Func<ScanStatistics, ScanStatistics> change)
        {
            lock (_gate)
            {
                Statistics = change(Statistics);
            }
        }

        public void Info(string code, string message) =>
            Diagnostics.Add(new AnalysisDiagnostic(DiagnosticSeverity.Info, code, message, Analyzer));

        public void Warn(string code, string message) =>
            Diagnostics.Add(new AnalysisDiagnostic(DiagnosticSeverity.Warning, code, message, Analyzer));

        public void FileInspected(string path)
        {
            lock (_gate)
            {
                _inspected++;
                _currentItem = path;
            }

            Report(force: false);
        }

        public void Report(bool force)
        {
            if (progress is null)
            {
                return;
            }

            AnalysisProgress report;
            lock (_gate)
            {
                var now = timeProvider.GetTimestamp();
                if (!force && _lastReport != long.MinValue && timeProvider.GetElapsedTime(_lastReport, now) < ProgressInterval)
                {
                    return;
                }

                _lastReport = now;
                report = new AnalysisProgress(AnalysisStage.Scanning, _inspected, Candidates.Count, _currentItem);
            }

            progress.Report(report);
        }
    }
}
