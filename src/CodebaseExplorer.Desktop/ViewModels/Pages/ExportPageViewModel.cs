using System.Collections.ObjectModel;
using CodebaseExplorer.Application.Export;
using CodebaseExplorer.Contracts.Export;
using CodebaseExplorer.Desktop.Services;
using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using Microsoft.Extensions.Logging;

namespace CodebaseExplorer.Desktop.ViewModels.Pages;

/// <summary>
/// Export page (EXPORT-002, USER_WORKFLOWS.md WF-08): scope (whole repository or the explorer's current view), sections,
/// target folder — by default the user's documents folder, outside the analyzed repository — and opening the folder after
/// the export. A target inside the analyzed repository (also an app-managed clone) needs an explicit confirmation
/// (SECURITY.md S5); the report itself is generated by <see cref="ExportArchitectureReport"/>.
/// </summary>
public sealed partial class ExportPageViewModel : PageViewModel
{
    private readonly ExportArchitectureReport _export;
    private readonly ArchitectureExplorerPageViewModel _explorer;
    private readonly RepositorySession _session;
    private readonly IFolderPicker _folderPicker;
    private readonly IFolderLauncher _folderLauncher;
    private readonly IReportFileWriter _writer;
    private readonly ShellStatus _shell;
    private readonly ILogger<ExportPageViewModel> _logger;

    public ExportPageViewModel(
        ExportArchitectureReport export,
        ArchitectureExplorerPageViewModel explorer,
        RepositorySession session,
        IFolderPicker folderPicker,
        IFolderLauncher folderLauncher,
        IReportFileWriter writer,
        ShellStatus shell,
        ILogger<ExportPageViewModel> logger)
    {
        _export = export;
        _explorer = explorer;
        _session = session;
        _folderPicker = folderPicker;
        _folderLauncher = folderLauncher;
        _writer = writer;
        _shell = shell;
        _logger = logger;

        Sections = [.. ReportSections.All.Select(s => new ExportSectionOption(s, SectionName(s)))];
        foreach (var section in Sections)
        {
            section.PropertyChanged += (_, _) => ExportCommand.NotifyCanExecuteChanged();
        }

        TargetFolder = DefaultTargetFolder();
        _session.CurrentChanged += (_, _) => Refresh();
        Refresh();
    }

    public override string Title => "Export";

    public override string Glyph => "⇩";

    /// <summary>Name of the repository to export; null without a current repository.</summary>
    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(HasRepository), nameof(ShowEmptyState))]
    [NotifyCanExecuteChangedFor(nameof(ExportCommand))]
    public partial string? RepositoryName { get; private set; }

    public bool HasRepository => RepositoryName is not null;

    public bool ShowEmptyState => !HasRepository;

    /// <summary>Report sections with their check state, in report order.</summary>
    public ObservableCollection<ExportSectionOption> Sections { get; }

    /// <summary>Scope: the explorer's current view instead of the whole repository.</summary>
    [ObservableProperty]
    public partial bool UseCurrentView { get; set; }

    /// <summary>True when the explorer shows a graph of the current repository, so "current view" can be chosen.</summary>
    [ObservableProperty]
    public partial bool CanUseCurrentView { get; private set; }

    /// <summary>Folder the report is written to.</summary>
    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(TargetIsInsideRepository))]
    [NotifyCanExecuteChangedFor(nameof(ExportCommand))]
    public partial string TargetFolder { get; set; }

    /// <summary>The target lies inside the analyzed repository: the user must confirm writing there.</summary>
    public bool TargetIsInsideRepository =>
        _session.Current is { } repository && !string.IsNullOrWhiteSpace(TargetFolder) && IsAbsolute(TargetFolder)
        && ReportFileWriter.IsInsideRepository(TargetFolder, repository.RootPath);

    /// <summary>Explicit confirmation to write into the analyzed repository (reset when the target changes).</summary>
    [ObservableProperty]
    [NotifyCanExecuteChangedFor(nameof(ExportCommand))]
    public partial bool ConfirmWriteIntoRepository { get; set; }

    [ObservableProperty]
    public partial bool OpenFolderAfterExport { get; set; } = true;

    [ObservableProperty]
    [NotifyCanExecuteChangedFor(nameof(ExportCommand))]
    public partial bool IsExporting { get; private set; }

    [ObservableProperty]
    public partial string? StatusMessage { get; private set; }

    [ObservableProperty]
    public partial string? ErrorMessage { get; private set; }

    public override Task ActivateAsync()
    {
        Refresh();
        return Task.CompletedTask;
    }

    partial void OnTargetFolderChanged(string value) => ConfirmWriteIntoRepository = false;

    [RelayCommand]
    private async Task ChooseFolderAsync(CancellationToken cancellationToken)
    {
        if (await _folderPicker.PickFolderAsync("Export to folder", cancellationToken) is { } folder)
        {
            TargetFolder = folder;
        }
    }

    [RelayCommand(CanExecute = nameof(CanExport))]
    private async Task ExportAsync(CancellationToken cancellationToken)
    {
        if (_session.Current is not { } repository)
        {
            return;
        }

        ErrorMessage = null;
        StatusMessage = null;
        IsExporting = true;
        using var operation = _shell.BeginOperation($"Exporting the architecture report of {repository.Name}");
        try
        {
            var view = UseCurrentView && CanUseCurrentView ? _explorer.CurrentQuery : null;
            var result = await _export.ExecuteAsync(new ArchitectureReportRequest
            {
                RepositoryId = repository.RepositoryId,
                Sections = [.. Sections.Where(s => s.IsSelected).Select(s => s.Token)],
                View = view,
            }, cancellationToken);
            if (!result.TryGetValue(out var report, out var error))
            {
                _logger.LogWarning("Export failed with {ErrorCode}", error.Code);
                ErrorMessage = error.Message;
                return;
            }

            var path = await _writer.WriteAsync(TargetFolder, report.FileName, report.Markdown, cancellationToken);
            StatusMessage = $"Saved {Path.GetFileName(path)} in {Path.GetDirectoryName(path)}." +
                (report.GraphTruncated ? " The diagram shows part of the graph; the report says what was left out." : string.Empty);
            if (OpenFolderAfterExport && !await _folderLauncher.OpenAsync(Path.GetDirectoryName(path)!))
            {
                StatusMessage += " The folder could not be opened.";
            }
        }
        catch (OperationCanceledException)
        {
            StatusMessage = "Export cancelled.";
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException or ArgumentException or NotSupportedException)
        {
            // The path is the user's own choice; the exception type is enough for the log.
            _logger.LogWarning("Writing the report failed with {ExceptionType}", exception.GetType().Name);
            ErrorMessage = $"The report could not be written to {TargetFolder}: {exception.Message}";
        }
        finally
        {
            IsExporting = false;
        }
    }

    private bool CanExport() =>
        HasRepository && !IsExporting && Sections.Any(s => s.IsSelected)
        && !string.IsNullOrWhiteSpace(TargetFolder) && IsAbsolute(TargetFolder)
        && (!TargetIsInsideRepository || ConfirmWriteIntoRepository);

    private void Refresh()
    {
        RepositoryName = _session.Current?.Name;
        CanUseCurrentView = _explorer.CurrentQuery is { } query && query.RepositoryId == _session.Current?.RepositoryId;
        if (!CanUseCurrentView)
        {
            UseCurrentView = false;
        }

        OnPropertyChanged(nameof(TargetIsInsideRepository));
        ExportCommand.NotifyCanExecuteChanged();
    }

    private static bool IsAbsolute(string path) => Path.IsPathFullyQualified(path.Trim());

    /// <summary>The user's documents folder (outside any analyzed repository by default), else the home folder.</summary>
    private static string DefaultTargetFolder()
    {
        var documents = Environment.GetFolderPath(Environment.SpecialFolder.MyDocuments);
        return documents.Length > 0 ? documents : Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
    }

    private static string SectionName(string token) => token switch
    {
        ReportSections.Overview => "Overview",
        ReportSections.Languages => "Languages",
        ReportSections.Projects => "Projects",
        ReportSections.DependencyGraph => "Dependency graph (Mermaid)",
        ReportSections.ExternalDependencies => "External dependencies",
        ReportSections.AnalysisMetadata => "Analysis metadata",
        ReportSections.EvidenceStatistics => "Evidence statistics",
        _ => token,
    };
}

/// <summary>One selectable report section.</summary>
public sealed partial class ExportSectionOption(string token, string name) : ViewModelBase
{
    public string Token { get; } = token;

    public string Name { get; } = name;

    [ObservableProperty]
    public partial bool IsSelected { get; set; } = true;
}
