using System.Globalization;
using System.Text;
using CodebaseExplorer.Contracts.Export;
using CodebaseExplorer.Contracts.Graph;
using CodebaseExplorer.Domain.Common;
using CodebaseExplorer.Domain.Evidence;
using CodebaseExplorer.Domain.Model;
using CodebaseExplorer.Domain.Projects;
using CodebaseExplorer.Domain.Relationships;
using CodebaseExplorer.Domain.Repositories;
using CodebaseExplorer.Domain.Runs;

namespace CodebaseExplorer.Application.Export;

/// <summary>Everything one report is generated from (EXPORT-001).</summary>
/// <param name="Repository">The repository (name, source).</param>
/// <param name="Run">The run that produced <paramref name="Model"/>.</param>
/// <param name="Model">The current model.</param>
/// <param name="Graph">The projected graph for the diagram.</param>
/// <param name="IsCurrentView">The diagram is the explorer's current view (not the whole repository).</param>
/// <param name="Sections">Section tokens in order (<see cref="ReportSections"/>).</param>
/// <param name="GeneratedAt">Time of generation.</param>
public sealed record ArchitectureReportData(
    Repository Repository,
    AnalysisRun Run,
    ArchitectureModel Model,
    GraphViewDto Graph,
    bool IsCurrentView,
    IReadOnlyList<string> Sections,
    DateTimeOffset GeneratedAt);

/// <summary>
/// Pure Markdown generation of the architecture report (EXPORT-001, MVP_SCOPE.md MVP-12): no I/O, deterministic for the
/// same input (sorted tables, invariant culture, UTC times, LF line endings). Repository-provided text is escaped
/// (<see cref="MarkdownText"/>, <see cref="MermaidDiagram"/>). Absolute local paths are not included.
/// </summary>
public static class MarkdownReportRenderer
{
    /// <summary>The report and whether its diagram omits part of the graph.</summary>
    public static (string Markdown, bool GraphTruncated) Render(ArchitectureReportData data)
    {
        ArgumentNullException.ThrowIfNull(data);
        var report = new Writer();
        var model = data.Model;
        report.Line($"# Architecture report: {MarkdownText.Escape(data.Repository.Name)}");
        report.Line();
        report.Line($"Generated by Codebase Explorer on {Utc(data.GeneratedAt)} from the analysis run of {Utc(data.Run.StartedAt)}. " +
            $"Scope: {(data.IsCurrentView ? "current graph view" : "whole repository")}.");
        report.Line("Every relationship is backed by evidence from static analysis; repository code was not executed.");

        var truncated = false;
        foreach (var section in data.Sections)
        {
            report.Line();
            switch (section)
            {
                case ReportSections.Overview:
                    Overview(report, data);
                    break;
                case ReportSections.Languages:
                    Languages(report, model);
                    break;
                case ReportSections.Projects:
                    Projects(report, model);
                    break;
                case ReportSections.DependencyGraph:
                    truncated = DependencyGraph(report, data);
                    break;
                case ReportSections.ExternalDependencies:
                    ExternalDependencies(report, model);
                    break;
                case ReportSections.AnalysisMetadata:
                    AnalysisMetadata(report, data.Run);
                    break;
                case ReportSections.EvidenceStatistics:
                    EvidenceStatistics(report, model);
                    break;
                default:
                    throw new ArgumentException($"Unknown report section '{section}'.", nameof(data));
            }
        }

        return (report.ToString(), truncated);
    }

    private static void Overview(Writer report, ArchitectureReportData data)
    {
        var model = data.Model;
        report.Line("## Overview");
        report.Line();
        report.Table(["Item", "Value"],
        [
            ["Repository", MarkdownText.Escape(data.Repository.Name)],
            ["Source", data.Repository.Location.RemoteUrl is { } url
                ? $"Clone of {MarkdownText.Escape(url.AbsoluteUri)}"
                : "Local folder"],
            ["Files", Number(model.Files.Count)],
            ["Lines", Number(model.Files.Sum(f => (long)(f.LineCount ?? 0)))],
            ["Projects", Number(model.Projects.Count(p => !p.IsPlaceholder()))],
            ["Referenced but missing projects", Number(model.Projects.Count(p => p.IsPlaceholder()))],
            ["Modules", Number(model.Modules.Count)],
            ["Code entities", Number(model.Entities.Count)],
            ["Relationships", Number(model.Relationships.Count)],
            ["External dependencies", Number(model.ExternalDependencies.Count)],
        ]);
    }

    private static void Languages(Writer report, ArchitectureModel model)
    {
        report.Line("## Languages");
        report.Line();
        report.Table(["Language", "Files", "Lines"],
            [.. model.Files
                .GroupBy(f => f.Language.Value, StringComparer.Ordinal)
                .OrderByDescending(g => g.Count()).ThenBy(g => g.Key, StringComparer.Ordinal)
                .Select(g => new[] { MarkdownText.Escape(g.Key), Number(g.Count()), Number(g.Sum(f => (long)(f.LineCount ?? 0))) })]);
    }

    private static void Projects(Writer report, ArchitectureModel model)
    {
        report.Line("## Projects");
        report.Line();
        var references = model.Relationships.Where(r => r.Kind == RelationshipKind.ProjectReference).ToList();
        var packages = model.Relationships.Where(r => r.Kind is RelationshipKind.PackageReference or RelationshipKind.FrameworkReference).ToList();
        report.Table(["Project", "Kind", "Language", "Folder", "Files", "References", "Referenced by", "Packages"],
            [.. model.Projects
                .OrderBy(p => p.Name, StringComparer.Ordinal).ThenBy(p => p.RootDirectory.Value, StringComparer.Ordinal)
                .Select(p => new[]
                {
                    MarkdownText.Escape(p.Name) + (p.IsPlaceholder() ? " (missing)" : string.Empty),
                    KindText(p.Kind),
                    MarkdownText.Escape(p.PrimaryLanguage.Value),
                    p.RootDirectory.Value.Length == 0 ? "(root)" : MarkdownText.Escape(p.RootDirectory.Value),
                    Number(model.Files.Count(f => f.ProjectId == p.Id)),
                    Number(references.Where(r => r.Source.Id == p.Id).Select(r => r.Target.Id).Distinct().Count()),
                    Number(references.Where(r => r.Target.Id == p.Id).Select(r => r.Source.Id).Distinct().Count()),
                    Number(packages.Where(r => r.Source.Id == p.Id).Select(r => r.Target.Id).Distinct().Count()),
                })]);
    }

    private static bool DependencyGraph(Writer report, ArchitectureReportData data)
    {
        report.Line("## Dependency graph");
        report.Line();
        var (diagram, omittedEdges) = MermaidDiagram.Render(data.Graph);
        report.Line(data.IsCurrentView
            ? "The graph as shown in the Architecture Explorer when the report was generated. Edge labels count the relationships; dotted edges rest on heuristic evidence only."
            : "Projects and their dependencies (project level, including test projects). Edge labels count the relationships; dotted edges rest on heuristic evidence only.");
        report.Line();
        report.Line("```mermaid");
        report.Raw(diagram);
        report.Line("```");

        var notes = new List<string>();
        if (data.Graph.Truncation is { } truncation)
        {
            notes.Add($"{Number(truncation.OmittedNodeCount)} elements are not shown (node budget); they are summarized in aggregate nodes.");
        }

        if (omittedEdges > 0)
        {
            notes.Add($"{Number(omittedEdges)} weaker edges are not shown (Mermaid shows at most {Number(MermaidDiagram.MaxEdges)} edges).");
        }

        foreach (var note in notes)
        {
            report.Line();
            report.Line($"> {note}");
        }

        return notes.Count > 0;
    }

    private static void ExternalDependencies(Writer report, ArchitectureModel model)
    {
        report.Line("## External dependencies");
        report.Line();
        if (model.ExternalDependencies.Count == 0)
        {
            report.Line("No external dependencies were found.");
            return;
        }

        var usedBy = model.Relationships.Where(r => r.Kind is RelationshipKind.PackageReference or RelationshipKind.FrameworkReference)
            .GroupBy(r => r.Target.Id)
            .ToDictionary(g => g.Key, g => g.Select(r => r.Source.Id).Distinct().Count());
        report.Table(["Package", "Ecosystem", "Used by projects"],
            [.. model.ExternalDependencies
                .OrderBy(d => d.Ecosystem.ToKeyToken(), StringComparer.Ordinal).ThenBy(d => d.DisplayName, StringComparer.Ordinal)
                .Select(d => new[] { MarkdownText.Escape(d.DisplayName), d.Ecosystem.ToKeyToken(), Number(usedBy.GetValueOrDefault(d.Id)) })]);
    }

    private static void AnalysisMetadata(Writer report, AnalysisRun run)
    {
        report.Line("## Analysis metadata");
        report.Line();
        report.Table(["Item", "Value"],
        [
            ["Status", run.Status switch
            {
                AnalysisRunStatus.Succeeded => "Succeeded",
                AnalysisRunStatus.PartiallySucceeded => "Partially succeeded",
                _ => run.Status.ToString(),
            }],
            ["Started", Utc(run.StartedAt)],
            ["Completed", run.CompletedAt is { } completed ? Utc(completed) : "—"],
            ["Commit", run.CommitSha is { } sha ? $"`{sha}`" : "— (not a Git repository)"],
            ["Branch", run.Branch is { } branch ? MarkdownText.Escape(branch) : "—"],
            ["Files scanned / skipped", $"{Number(run.Statistics.FilesScanned)} / {Number(run.Statistics.FilesSkipped)}"],
            ["Warnings", Number(run.Diagnostics.Count(d => d.Severity == DiagnosticSeverity.Warning))],
            ["Errors", Number(run.Diagnostics.Count(d => d.Severity == DiagnosticSeverity.Error))],
        ]);
        if (run.AnalyzerVersions.Count > 0)
        {
            report.Line();
            report.Table(["Analyzer", "Version"],
                [.. run.AnalyzerVersions.OrderBy(a => a.Key, StringComparer.Ordinal)
                    .Select(a => new[] { MarkdownText.Escape(a.Key), MarkdownText.Escape(a.Value) })]);
        }
    }

    private static void EvidenceStatistics(Writer report, ArchitectureModel model)
    {
        report.Line("## Evidence statistics");
        report.Line();
        report.Line("Evidence levels: *confirmed* (semantic model or authoritative declaration), *syntactic* (syntax or manifest, resolved by name or path), *heuristic* (pattern or convention).");
        report.Line();
        EvidenceLevel[] levels = [EvidenceLevel.Confirmed, EvidenceLevel.Syntactic, EvidenceLevel.Heuristic];
        report.Table(["Relationship kind", .. levels.Select(LevelText), "Total"],
            [.. model.Relationships
                .GroupBy(r => r.Kind.ToKeyToken(), StringComparer.Ordinal)
                .OrderBy(g => g.Key, StringComparer.Ordinal)
                .Select(g => (string[])[g.Key, .. levels.Select(l => Number(g.Count(r => r.Level == l))), Number(g.Count())])
                .Append(["**All**", .. levels.Select(l => Number(model.Relationships.Count(r => r.Level == l))), Number(model.Relationships.Count)])]);
        report.Line();
        var evidence = model.Relationships.SelectMany(r => r.Evidence).ToList();
        report.Table(["Analyzer", "Evidence records"],
            [.. evidence.GroupBy(e => e.Analyzer.Value, StringComparer.Ordinal)
                .OrderBy(g => g.Key, StringComparer.Ordinal)
                .Select(g => new[] { MarkdownText.Escape(g.Key), Number(g.Count()) })
                .Append(["**All**", Number(evidence.Count)])]);
    }

    private static string LevelText(EvidenceLevel level) => level switch
    {
        EvidenceLevel.Confirmed => "Confirmed",
        EvidenceLevel.Syntactic => "Syntactic",
        _ => "Heuristic",
    };

    private static string KindText(ProjectKind kind) => kind switch
    {
        ProjectKind.DotNetProject => ".NET project",
        ProjectKind.NodePackage => "Node package",
        ProjectKind.NodeWorkspaceRoot => "Node workspace root",
        ProjectKind.PythonProject => "Python project",
        ProjectKind.PythonPackageFolder => "Python package folder",
        _ => "Unknown",
    };

    private static string Number(long value) => value.ToString("N0", CultureInfo.InvariantCulture);

    private static string Utc(DateTimeOffset time) => time.UtcDateTime.ToString("yyyy-MM-dd HH:mm 'UTC'", CultureInfo.InvariantCulture);

    /// <summary>Line-based writer with LF endings.</summary>
    private sealed class Writer
    {
        private readonly StringBuilder _builder = new();

        public void Line(string text = "") => _builder.Append(text).Append('\n');

        public void Raw(string text) => _builder.Append(text);

        public void Table(IReadOnlyList<string> header, IEnumerable<IReadOnlyList<string>> rows)
        {
            Line("| " + string.Join(" | ", header) + " |");
            Line("|" + string.Concat(header.Select(_ => "---|")));
            foreach (var row in rows)
            {
                Line("| " + string.Join(" | ", row) + " |");
            }
        }

        public override string ToString() => _builder.ToString();
    }
}
