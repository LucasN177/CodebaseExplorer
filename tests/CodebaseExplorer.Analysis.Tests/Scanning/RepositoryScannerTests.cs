using System.Diagnostics;
using System.Security.Cryptography;
using System.Text;
using CodebaseExplorer.Analysis.FileSystem;
using CodebaseExplorer.Analysis.Scanning;
using CodebaseExplorer.Application.Analysis;
using CodebaseExplorer.Application.Repositories;
using CodebaseExplorer.Domain.Files;
using CodebaseExplorer.Domain.Runs;
using CodebaseExplorer.TestRepositories;

namespace CodebaseExplorer.Analysis.Tests.Scanning;

public sealed class RepositoryScannerTests : IDisposable
{
    private readonly TempDirectory _repo = new();
    private readonly RepositoryScanner _scanner = new(new RepositoryFileReader(), TimeProvider.System);

    public void Dispose() => _repo.Dispose();

    private RepositoryRoot Root => new(_repo.FullPath);

    private Task<ScanResult> ScanAsync(AnalysisLimits? limits = null, IProgress<AnalysisProgress>? progress = null) =>
        _scanner.ScanAsync(Root, limits ?? AnalysisLimits.Default, progress, TestContext.Current.CancellationToken);

    [Fact]
    public async Task Scan_ReturnsFilesSortedOrdinallyWithHashAndLineCount()
    {
        _repo.WriteText("src/b.cs", "line1\nline2\n");
        _repo.WriteText("src/a.cs", "line1\nline2");
        _repo.WriteText("README.md", string.Empty);
        _repo.WriteText("Z.txt", "z");

        var result = await ScanAsync();

        Assert.Equal(["README.md", "Z.txt", "src/a.cs", "src/b.cs"], result.Files.Select(f => f.Path.Value));

        var b = result.Files.Single(f => f.Path.Value == "src/b.cs");
        Assert.Equal(Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes("line1\nline2\n"))), b.Hash.ToString());
        Assert.Equal(12, b.SizeBytes);
        Assert.Equal(2, b.LineCount);
        Assert.Equal(2, result.Files.Single(f => f.Path.Value == "src/a.cs").LineCount);
        Assert.Equal(0, result.Files.Single(f => f.Path.Value == "README.md").LineCount);
        Assert.Equal(4, result.Statistics.FilesScanned);
    }

    [Fact]
    public async Task BuiltInExcludes_AreNotDescendedIntoAndCounted()
    {
        _repo.WriteText("src/a.cs", "a");
        _repo.WriteText("src/bin/Debug/a.dll", "x");
        _repo.WriteText("src/obj/project.assets.json", "{}");
        _repo.WriteText("web/node_modules/react/index.js", "x");
        _repo.WriteText(".git/HEAD", "ref: refs/heads/main");

        var result = await ScanAsync();

        Assert.Equal(["src/a.cs"], result.Files.Select(f => f.Path.Value));
        Assert.Equal(4, result.Statistics.DirectoriesExcluded);
    }

    [Fact]
    public async Task ExcludedDirectoryNames_AreConfigurable()
    {
        _repo.WriteText("build/script.sh", "echo");
        _repo.WriteText("custom/x.txt", "x");

        var result = await ScanAsync(AnalysisLimits.Default with { ExcludedDirectoryNames = ["custom"] });

        Assert.Equal(["build/script.sh"], result.Files.Select(f => f.Path.Value));
    }

    [Fact]
    public async Task GitIgnore_ExcludesFilesAndDirectoriesAndSupportsNegation()
    {
        _repo.WriteText(".gitignore", "*.log\n!keep.log\ncoverage/\n/local.txt\n");
        _repo.WriteText("a.log", "x");
        _repo.WriteText("keep.log", "x");
        _repo.WriteText("sub/b.log", "x");
        _repo.WriteText("coverage/report.html", "x");
        _repo.WriteText("local.txt", "x");
        _repo.WriteText("sub/local.txt", "x");

        var result = await ScanAsync();

        Assert.Equal([".gitignore", "keep.log", "sub/local.txt"], result.Files.Select(f => f.Path.Value));
        Assert.Equal(3, result.Statistics.FilesIgnored);
        Assert.Equal(1, result.Statistics.DirectoriesIgnored);
    }

    [Fact]
    public async Task NestedGitIgnore_AppliesToItsSubtreeAndOverridesParent()
    {
        _repo.WriteText(".gitignore", "*.tmp\n");
        _repo.WriteText("pkg/.gitignore", "!keep.tmp\n*.cache\n");
        _repo.WriteText("pkg/keep.tmp", "x");
        _repo.WriteText("pkg/drop.tmp", "x");
        _repo.WriteText("pkg/a.cache", "x");
        _repo.WriteText("root.cache", "x");

        var result = await ScanAsync();

        Assert.Equal([".gitignore", "pkg/.gitignore", "pkg/keep.tmp", "root.cache"], result.Files.Select(f => f.Path.Value));
    }

    [Fact]
    public async Task FilesInIgnoredDirectory_CannotBeReIncluded()
    {
        _repo.WriteText(".gitignore", "generated/\n!generated/keep.cs\n");
        _repo.WriteText("generated/keep.cs", "x");

        var result = await ScanAsync();

        Assert.DoesNotContain(result.Files, f => f.Path.Value == "generated/keep.cs");
    }

    [Fact]
    public async Task BinaryAndGeneratedAndTestFiles_AreClassified()
    {
        _repo.WriteBytes("assets/logo.png", [0x89, 0x50, 0x00, 0x47]);
        _repo.WriteText("src/Api.cs", "// <auto-generated>\nclass Api {}\n");
        _repo.WriteText("src/Billing.Tests/T.cs", "class T {}");
        _repo.WriteText("src/A.cs", "class A {}");

        var result = await ScanAsync();
        var byPath = result.Files.ToDictionary(f => f.Path.Value);

        Assert.True(byPath["assets/logo.png"].IsBinary);
        Assert.Null(byPath["assets/logo.png"].LineCount);
        Assert.Equal(FileClassification.Binary, byPath["assets/logo.png"].Classification);
        Assert.True(byPath["src/Api.cs"].HasGeneratedHeader);
        Assert.Equal(FileClassification.Generated, byPath["src/Api.cs"].Classification);
        Assert.Equal(FileClassification.Test, byPath["src/Billing.Tests/T.cs"].Classification);
        Assert.Equal(FileClassification.Source, byPath["src/A.cs"].Classification);
    }

    [Fact]
    public async Task Scan_DetectsLanguagesAndProjectMarkers()
    {
        _repo.WriteText("Shop.slnx", "<Solution />");
        _repo.WriteText("src/Billing/Billing.csproj", "<Project />");
        _repo.WriteText("src/Billing/Invoice.cs", "class Invoice {}");
        _repo.WriteText("web/package.json", "{}");
        _repo.WriteText("tools/run", "#!/usr/bin/env python3\nprint(1)\n");
        _repo.WriteText("LICENSE", "MIT");

        var byPath = (await ScanAsync()).Files.ToDictionary(f => f.Path.Value);

        Assert.Equal(ProjectMarker.DotNetSolutionXml, byPath["Shop.slnx"].Marker);
        Assert.Equal(FileClassification.SolutionFile, byPath["Shop.slnx"].Classification);
        Assert.Equal(ProjectMarker.DotNetProject, byPath["src/Billing/Billing.csproj"].Marker);
        Assert.Equal("xml", byPath["src/Billing/Billing.csproj"].Language.Value);
        Assert.Equal("csharp", byPath["src/Billing/Invoice.cs"].Language.Value);
        Assert.Null(byPath["src/Billing/Invoice.cs"].Marker);
        Assert.Equal(ProjectMarker.NodePackage, byPath["web/package.json"].Marker);
        Assert.Equal("python", byPath["tools/run"].Language.Value);
        Assert.Equal(FileClassification.Source, byPath["tools/run"].Classification);
        Assert.Equal("unknown", byPath["LICENSE"].Language.Value);
        Assert.Equal(FileClassification.Other, byPath["LICENSE"].Classification);
    }

    [Fact]
    public async Task NulByteAfterSniffWindow_IsNotBinary()
    {
        var content = Encoding.ASCII.GetBytes(new string('a', 9000)).Concat(new byte[] { 0 }).ToArray();
        _repo.WriteBytes("big.txt", content);

        var result = await ScanAsync();

        Assert.False(Assert.Single(result.Files).IsBinary);
    }

    [Fact]
    public async Task Scan_IsDeterministic()
    {
        for (var i = 0; i < 30; i++)
        {
            _repo.WriteText($"d{i % 4}/f{i}.txt", $"content {i}");
        }

        var first = await ScanAsync();
        var second = await ScanAsync();

        Assert.Equal(first.Files.Select(f => (f.Path, f.Hash.ToString())), second.Files.Select(f => (f.Path, f.Hash.ToString())));
    }

    [Fact]
    public async Task FileLimit_TruncatesWithWarning()
    {
        for (var i = 0; i < 5; i++)
        {
            _repo.WriteText($"f{i}.txt", "x");
        }

        var result = await ScanAsync(AnalysisLimits.Default with { MaxFiles = 3 });

        Assert.Equal(3, result.Files.Count);
        Assert.True(result.Statistics.Truncated);
        Assert.Contains(result.Diagnostics, d => d.Code == "scan.file-limit-reached" && d.Severity == DiagnosticSeverity.Warning);
    }

    [Fact]
    public async Task DepthLimit_SkipsDeepDirectoriesWithWarning()
    {
        _repo.WriteText("a/b/c/deep.txt", "x");
        _repo.WriteText("a/shallow.txt", "x");

        var result = await ScanAsync(AnalysisLimits.Default with { MaxDirectoryDepth = 2 });

        Assert.Equal(["a/shallow.txt"], result.Files.Select(f => f.Path.Value));
        Assert.Equal(1, result.Statistics.DirectoriesTooDeep);
        Assert.Contains(result.Diagnostics, d => d.Code == "scan.directory-too-deep");
    }

    [Fact]
    public async Task Junction_IsNotFollowed()
    {
        _repo.WriteText("real/a.txt", "x");
        if (!_repo.TryCreateJunction("alias", _repo.PathOf("real")))
        {
            Assert.Skip("Directory junctions exist only on Windows.");
        }

        var result = await ScanAsync();

        Assert.Equal(["real/a.txt"], result.Files.Select(f => f.Path.Value));
        Assert.Equal(1, result.Statistics.LinksSkipped);
        Assert.Contains(result.Diagnostics, d => d.Code == RepositoryErrorCodes.FileLinkNotFollowed && d.Severity == DiagnosticSeverity.Info);
    }

    [Fact]
    public async Task OversizedGitIgnore_IsReportedAndNotApplied()
    {
        _repo.WriteText(".gitignore", "*.log\n" + new string('#', 100));
        _repo.WriteText("a.log", "x");

        var result = await ScanAsync(AnalysisLimits.Default with { MaxManifestBytes = 10 });

        Assert.Contains(result.Files, f => f.Path.Value == "a.log");
        Assert.Contains(result.Diagnostics, d => d.Code == RepositoryErrorCodes.FileTooLarge && d.Severity == DiagnosticSeverity.Warning);
    }

    [Fact]
    public async Task Progress_ReportsScanningStage()
    {
        _repo.WriteText("a.txt", "x");
        _repo.WriteText("b.txt", "x");
        var progress = new CollectingProgress();

        await ScanAsync(progress: progress);

        Assert.NotEmpty(progress.Reports);
        Assert.All(progress.Reports, p => Assert.Equal(AnalysisStage.Scanning, p.Stage));
        Assert.Equal(2, progress.Reports[^1].Processed);
        Assert.Equal(2, progress.Reports[^1].Total);
    }

    [Fact]
    public async Task Cancellation_Throws()
    {
        _repo.WriteText("a.txt", "x");
        using var cancelled = new CancellationTokenSource();
        await cancelled.CancelAsync();

        await Assert.ThrowsAnyAsync<OperationCanceledException>(() =>
            _scanner.ScanAsync(Root, AnalysisLimits.Default, null, cancelled.Token));
    }

    /// <summary>Smoke benchmark (REPO-002, not a CI gate). Run with: --filter-method "*Scan_TenThousandFiles*".</summary>
    [Fact(Explicit = true)]
    public async Task Scan_TenThousandFiles_CompletesWithinFiveSeconds()
    {
        for (var i = 0; i < 10_000; i++)
        {
            _repo.WriteText($"d{i % 100}/f{i}.cs", $"class C{i} {{ }}\n");
        }

        var stopwatch = Stopwatch.StartNew();
        var result = await ScanAsync();
        stopwatch.Stop();

        TestContext.Current.TestOutputHelper?.WriteLine($"Scanned {result.Files.Count} files in {stopwatch.ElapsedMilliseconds} ms.");
        Assert.Equal(10_000, result.Files.Count);
        Assert.True(stopwatch.Elapsed < TimeSpan.FromSeconds(5), $"Scan took {stopwatch.Elapsed}.");
    }

    private sealed class CollectingProgress : IProgress<AnalysisProgress>
    {
        public List<AnalysisProgress> Reports { get; } = [];

        public void Report(AnalysisProgress value) => Reports.Add(value);
    }
}
